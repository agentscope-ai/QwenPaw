def build_defect_question_block(*, multi_shot_expected: bool) -> str:
    """User-text section listing every applicable bank question."""
    lines = [
        "【固定缺陷题清单（universal defects，逐题判 ET/CT/NA）】",
        "以下为固定基线题库（近失误极性）：ET=确认无此缺陷，CT=确认存在（必须给出证据帧时间戳与修改建议），NA=不适用（必须给出理由）。",
        "适用性门控：动画/插画/强风格化素材对「AI塑料质感」「穿模悬浮」判 NA 并说明；画面中无人物时「肢体畸变」判 NA；单镜头视频对跨镜类题判 NA。",
    ]
    for defect in UNIVERSAL_DEFECTS:
        if not multi_shot_expected and defect.applicability == "multi_shot":
            continue
        lines.append(
            f"- {defect.defect_id}（{defect.title}，{defect.severity}）：{defect.question}",
        )
    return "\n".join(lines)


def program_defect_hints(
    objective_facts: Mapping[str, Any] | None,
) -> str:
    """Tier-0 evidence lines attached to their bank questions."""
    if not objective_facts:
        return ""
    lines: list[str] = []
    index = objective_facts.get("video_index") or {}
    if isinstance(index, Mapping):
        cut_count = index.get("cut_count")
        planned = index.get("planned_shot_count")
        if cut_count is not None:
            actual_shots = int(cut_count) + 1
            hint = f"程序检测到 {cut_count} 个切点（约 {actual_shots} 个镜头）"
            if planned:
                hint += f"，计划 {planned} 个镜头"
            lines.append(f"- uq_shot_count 证据：{hint}。")
        freezes = index.get("freeze_segments") or []
        if freezes:
            spans = ", ".join(
                f"{seg.get('start_ms')}–{seg.get('end_ms')}ms"
                for seg in freezes[:4]
                if isinstance(seg, Mapping)
            )
            lines.append(
                f"- uq_render_3 证据：程序检测到疑似静止段 {spans}" "（可能是合法定格，请看对应帧确认）。",
            )
    consistency = objective_facts.get("cross_shot_consistency") or {}
    if isinstance(consistency, Mapping):
        for pair in (consistency.get("suspect_pairs") or [])[:2]:
            if isinstance(pair, Mapping):
                lines.append(
                    "- uq_subject_1 证据：程序发现疑似主体不一致镜头对 "
                    f"t={pair.get('frame_a_ms')}ms vs t={pair.get('frame_b_ms')}ms"
                    "（同人换角度也会触发，请看画面确认）。",
                )
    if not lines:
        return ""
    return "【题库程序证据提示】\n" + "\n".join(lines)


