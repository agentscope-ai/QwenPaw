"""Universal defect bank (tier-2): fixed near-miss questions per video.

Ported from APE-benchmark ``grader/rubrics/universal_defects.json`` (v3):
a hand-maintained question bank that is injected programmatically — never
generated by an LLM — so every reviewed video is measured with the same
ruler and results stay reproducible. Question polarity is near-miss
(ET = confirmed ABSENT, CT = present, NA = not applicable); an NA must
carry a reason and a CT must carry frame evidence, both enforced by the
parser (anti-hallucination).

The two rows that a program can evidence directly (shot count, freeze /
black screens) get their tier-0 facts attached as hints; the VLM still
issues the verdict on the focused frames.
"""

