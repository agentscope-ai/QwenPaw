# -*- coding: utf-8 -*-
"""Generate portable schemas and TypeScript types; --check fails on drift."""

import argparse
import json
from pathlib import Path

from qwenpaw.pawapp.contracts import schema_bundle

ROOT = Path(__file__).resolve().parents[1]


# pylint: disable-next=too-many-return-statements
def ts(schema):
    if schema is True or schema == {}:
        return "unknown"
    if schema is False:
        return "never"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(v) for v in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == "object":
        properties = schema.get("properties", {})
        if not properties:
            return (
                f"Record<string, {ts(schema.get('additionalProperties', {}))}>"
            )
        required = schema.get("required", [])
        return (
            "{\n"
            + "\n".join(
                f"  {json.dumps(k)}{'' if k in required else '?'}: {ts(v)};"
                for k, v in properties.items()
            )
            + "\n}"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bundle = schema_bundle()
    definitions = bundle["$defs"]
    types = (
        "// Generated by scripts/generate-pawapp-contracts.py. Do not edit.\n"
    )
    types += "\n\n".join(
        f"export type {name} = {ts(schema)};"
        for name, schema in sorted(definitions.items())
    )
    types += (
        "\n\nexport interface ContractMap {\n"
        + "\n".join(f"  {name}: {name};" for name in sorted(definitions))
        + "\n}\n"
    )
    types += (
        "export const contractSchemas = "
        + json.dumps(definitions, separators=(",", ":"))
        + ";\n"
    )
    outputs = {
        ROOT
        / "docs/design/pawapp-contract-v1.schema.json": json.dumps(
            bundle,
            indent=2,
        )
        + "\n",
        ROOT / "console/src/plugins/pawapp-sdk/contracts.generated.ts": types,
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(
                    f"Generated contract drift: {path.relative_to(ROOT)}",
                )
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
