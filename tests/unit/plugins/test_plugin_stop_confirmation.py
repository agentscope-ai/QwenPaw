# -*- coding: utf-8 -*-
"""Run generic stop confirmation without repository-wide SDK mocks."""

import os
from pathlib import Path
import subprocess
import sys


def test_generic_stop_confirmation(tmp_path):
    suite = (
        Path(__file__).resolve().parents[2]
        / "fixtures/plugin_execution/stop_confirmation_suite.py"
    )
    result = subprocess.run(
        [
            sys.executable,
            "-I",
            "-m",
            "pytest",
            "--confcutdir",
            str(suite.parent),
            str(suite),
            "-q",
        ],
        env={
            **os.environ,
            "QWENPAW_WORKING_DIR": str(tmp_path / "host"),
            "QWENPAW_SECRET_DIR": str(tmp_path / "secrets"),
            "QWENPAW_BACKUP_DIR": str(tmp_path / "backups"),
        },
        capture_output=True,
        text=True,
        check=False,
        timeout=120,
    )
    assert result.returncode == 0, result.stdout + result.stderr
